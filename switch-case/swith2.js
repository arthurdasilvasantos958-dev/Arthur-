const sistema = "Windows";


switch (sistema) {
  case "Windows":
    console.log("Sistema operacional da Microsoft");
    break;


  case "Linux":
    console.log("Sistema operacional de código aberto");
    break;


  case "macOS":
    console.log("Sistema operacional da Apple");
    break;


  default:
    console.log("Sistema operacional não cadastrado");
}
